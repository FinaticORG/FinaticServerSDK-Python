#!/usr/bin/env python3
"""Generate raw-dictionary response types from the pinned OpenAPI artifact."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
ARTIFACT = ROOT / "artifacts/openapi/finaticapi-v1.json"
OUTPUT = ROOT / "src/finatic_fdx_typed_dicts.py"
ROOT_SCHEMAS = (
    "FDXBrokerOrder",
    "FDXBrokerOrderCommandResult",
    "FDXBrokerOrderEvent",
    "FDXBrokerOrderFill",
    "FDXBrokerPosition",
)


def ref_name(schema: dict[str, Any]) -> str | None:
    ref = schema.get("$ref")
    return ref.rsplit("/", 1)[-1] if isinstance(ref, str) else None


def annotation(schema: dict[str, Any], schemas: dict[str, Any]) -> str:
    name = ref_name(schema)
    if name:
        target = schemas[name]
        if target.get("type") == "object" or "properties" in target:
            return f"{name}Dict"
        return annotation(target, schemas)
    variants = schema.get("anyOf") or schema.get("oneOf")
    if variants:
        rendered = list(dict.fromkeys(annotation(item, schemas) for item in variants))
        return " | ".join(rendered)
    enum = schema.get("enum")
    if enum:
        return "Literal[" + ", ".join(repr(value) for value in enum) + "]"
    kind = schema.get("type")
    if kind == "array":
        return f"list[{annotation(schema.get('items', {}), schemas)}]"
    if kind == "object":
        return "dict[str, Any]"
    return {
        "boolean": "bool",
        "integer": "int",
        "number": "float",
        "null": "None",
        "string": "str",
    }.get(kind, "Any")


def referenced_objects(name: str, schemas: dict[str, Any], found: set[str]) -> None:
    if name in found:
        return
    schema = schemas[name]
    if schema.get("type") != "object" and "properties" not in schema:
        return
    found.add(name)

    def visit(value: Any) -> None:
        if isinstance(value, dict):
            dependency = ref_name(value)
            if dependency:
                referenced_objects(dependency, schemas, found)
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)

    visit(schema.get("properties", {}))


def render() -> str:
    document = json.loads(ARTIFACT.read_text(encoding="utf-8"))
    schemas: dict[str, Any] = document["components"]["schemas"]
    objects: set[str] = set()
    for name in ROOT_SCHEMAS:
        referenced_objects(name, schemas, objects)

    lines = [
        '"""Artifact-generated mapping types for the raw v1 facade.',
        "",
        "Generated by scripts/generate_fdx_typeddicts.py; do not edit.",
        '"""',
        "",
        "# isort: skip_file",
        "# fmt: off",
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal",
        "",
        "from typing_extensions import TypedDict",
        "",
        "",
    ]
    for name in sorted(objects):
        properties = schemas[name].get("properties", {})
        lines.append(f"class {name}Dict(TypedDict, total=False):")
        if not properties:
            lines.append("    pass")
        for field, field_schema in properties.items():
            lines.append(f"    {field}: {annotation(field_schema, schemas)}")
        lines.append("")
        lines.append("")
    exported = [f"{name}Dict" for name in ROOT_SCHEMAS]
    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for name in exported)
    lines.append("]")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(f"generated mapping type drift: {OUTPUT.relative_to(ROOT)}")
            return 1
        print("Artifact-generated mapping types are reproducible.")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"updated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
